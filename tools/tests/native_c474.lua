return function()
    local Motion=require("OMHTT/DefenseMotion")
    local Displacement=require("OMHTT/DefenseDisplacement")
    local actor=IsoZombie.new(getCell())
    actor:setHealth(1)
    actor:setX(14710.5);actor:setY(14710.5)
    actor:setStaggerBack(false)
    assert(Motion.request(actor,"push","c474-tether",14708,14710.5,.35),"Native push request rejected")
    assert(actor:isStaggerBack() and math.abs(actor:getHitForce())<.00001,"Native push must select a visible stagger without extra hit force")
    assert(actor:getHitDir():getX()>.99 and math.abs(actor:getHitDir():getY())<.001,"Native shove direction must point away from muzzle")
    actor:setStaggerBack(false)
    Motion.request(actor,"pull","c474-tether",14708,14710.5,.75)
    assert(not actor:isStaggerBack(),"Retraction must not restart outward shove")
    Displacement.clear(actor)
    print("[OMHTT-C474] native-tether standingReaction=stagger direction=away force=0 pull=no-retrigger")
end

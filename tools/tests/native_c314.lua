return function(player, controller, turret)
    local T = require("OMHTT/Turret")
    local C = require("OMHTT/ControlWorld")
    local Swap = require("OMHTT/TurretModuleSwap")
    local S = require("OMHTT/TurretSiphon")
    local B = require("OMHTT/TurretBattery")
    local stock, storage = controller:getContainer(), turret:getContainer()
    local id = T.state(turret).id
    local outgoing = storage:AddItem(T.TYPES.Firing)
    local incoming = stock:AddItem(T.TYPES.FiringEnhanced)
    local spare = storage:AddItem(T.TYPES.Siphon)
    assert(math.abs(spare:getActualWeight() - .2) < .000001, "Siphon weight must be 0.2")
    local action = Swap:new(player, turret, incoming, outgoing, id, controller)
    if not action:isValid() then
        local summary=T.contents(storage)
        print("[OMHTT-C314] swap diagnostic near="..tostring(require("OMHTT/TurretAccess").near(player,turret,id))
            .." source="..tostring(require("OMHTT/ControlAccess").stockpile(player,turret,controller)==controller)
            .." sourceAllows="..tostring(stock:isItemAllowed(outgoing))
            .." sourceRemove="..tostring(stock:isRemoveItemAllowed(incoming))
            .." targetRemove="..tostring(storage:isRemoveItemAllowed(outgoing))
            .." modules="..tostring(summary.modules).." capacity="..tostring(T.cycleConfig(summary).modules))
    end
    assert(action:isValid(), "Native exact-slot swap admission failed")
    local native = NetTimedAction.new()
    native:set(player, action)
    assert(action:isValid() and action:complete() and not action:complete(), "Native exact-slot swap/replay failed")
    assert(incoming:getContainer() == storage and outgoing:getContainer() == stock, "Swap changed item identity/source destination")
    assert(Swap.modules(turret)[1] == incoming, "Replacement lost the selected slot")
    local reorder = Swap:new(player, turret, incoming, spare, id, controller)
    assert(reorder:complete() and Swap.modules(turret)[1] == spare and Swap.modules(turret)[2] == incoming,
        "Same-turret reorder changed contents or lost exact positions")
    incoming:setFavorite(true)
    assert(not Swap:new(player,turret,outgoing,incoming,id,controller):complete(), "Favorite installed module was replaced")
    incoming:setFavorite(false)
    local forbidden = stock:AddItem(T.TYPES.Synergy)
    local existing = storage:AddItem(T.TYPES.Synergy)
    assert(not Swap:new(player,turret,forbidden,spare,id,controller):complete(), "Exclusive module duplicate accepted")
    assert(forbidden:getContainer() == stock and spare:getContainer() == storage, "Rejected swap changed inventory")
    stock:Remove(forbidden)
    storage:Remove(existing)
    local battery = storage:AddItem("Base.CarBattery1")
    battery:setCurrentUsesFloat(.5)
    local stats = T.cycleConfig(T.contents(storage))
    assert(stats.siphon == 2, "Native Siphon module not active")
    local before = B.charge(battery)
    local spent = B.spend(battery, .001234)
    local energy = S.capture(turret,{kind="battery",battery=battery},stats,spent)
    assert(energy and energy.source == C.state(turret).id, "Paid root lost authoritative device identity")
    local victim = IsoZombie.new(getCell())
    victim:setHealth(0)
    S.hit(victim,energy,false)
    S.hit(victim,energy,false)
    assert(energy.kills == 1 and math.abs(B.charge(battery) - before - spent) < .0000001,
        "Native fractional refund or server duplicate-death guard failed")
    local persisted = require("OMHTT/TurretItemState").get(battery,"battery")
    assert(persisted and battery:getModData().OMHTTBatteryDrain.debt == persisted.debt, "Refund left replicated fractional charge stale")
    before = B.charge(battery)
    B.detach(battery)
    local other = IsoZombie.new(getCell())
    other:setHealth(0)
    S.hit(other,energy,false)
    assert(B.charge(battery) == before,"Detached original battery accepted stale refund")
    storage:Remove(battery)
    storage:Remove(spare)
    storage:Remove(incoming)
    stock:Remove(outgoing)
    print("[OMHTT-C314] native swap=exact reorder=passed exclusive=blocked replay=blocked action=serialized siphon=fractional duplicate-death=blocked detach=blocked")
end
